import Foundation

/// Evidence-based completion and cross-agent handoff (spec Phase 5).
///
/// Both are pure compositions of data StackPulse already holds — the mission
/// (project, branch, changed files, scope flags, latest turn), the captured
/// command runs (did the tests actually pass?), and any checkpoints. Nothing here
/// reads the disk or the network; it only joins what's already in the store, so
/// it's safe to call from a view.
///
/// The honesty rule throughout: **absence of evidence is reported as absence**,
/// never as success. "An agent stopped talking" is not "the work is done" — only
/// a real, timestamped run outcome is.
enum MissionEvidence {
    /// The most recent captured run belonging to `mission`'s project, or `nil`
    /// when we have none. Matching is by the run's working directory, which is the
    /// same path the mission records — so a run from an unrelated project can't be
    /// passed off as this mission's evidence.
    static func latestRun(for mission: Mission, in runs: [CommandRun]) -> CommandRun? {
        guard let path = mission.project_path, !path.isEmpty else { return nil }
        return runs
            .filter { $0.cwd == path && $0.status.isFinished }
            .max(by: { $0.startedAtUnix < $1.startedAtUnix })
    }

    /// The most recent *verifying* run (a test/check), which is stronger evidence
    /// than any run at all. Falls back to `nil` rather than pretending a build or
    /// a lint counts as a test.
    static func latestVerification(for mission: Mission, in runs: [CommandRun]) -> CommandRun? {
        guard let path = mission.project_path, !path.isEmpty else { return nil }
        return runs
            .filter { $0.cwd == path && $0.status.isFinished && looksVerifying($0) }
            .max(by: { $0.startedAtUnix < $1.startedAtUnix })
    }

    /// Whether a run actually checks something (tests/typecheck), as opposed to
    /// merely building or starting a server.
    private static func looksVerifying(_ run: CommandRun) -> Bool {
        let hay = (run.label + " " + run.command).lowercased()
        return ["test", "vitest", "jest", "pytest", "typecheck", "type-check", "tsc", "check", "lint"]
            .contains { hay.contains($0) }
    }

    /// Whether the run happened after the mission's work started — evidence from
    /// *before* the session began says nothing about what the agent just did.
    ///
    /// An unknown start time returns `false`, not `true`. `started_at_unix` is
    /// genuinely optional on the wire, and defaulting the unknown case to "yes"
    /// turned "we don't know when this session began" into "this run post-dates
    /// it" — rendering a green *verified* tick from evidence we can't place. This
    /// module's whole rule is that absence of evidence is reported as absence.
    static func isAfterSessionStart(_ run: CommandRun, _ mission: Mission) -> Bool {
        guard let started = mission.started_at_unix else { return false }
        return run.startedAtUnix >= Double(started)
    }
}

// MARK: - Handoff package

/// A portable summary of what an agent session actually did, for handing the work
/// to another agent (or to yourself next week): what it touched, what that change
/// risks, whether anything verified it, and how to get back.
enum HandoffPackage {
    /// Compose the package as Markdown. Every section is omitted rather than
    /// padded when the underlying data is absent, so the reader can tell the
    /// difference between "nothing changed" and "we don't know".
    static func markdown(mission: Mission,
                         evidence: CommandRun?,
                         verification: CommandRun?,
                         checkpoints: [Checkpoint],
                         generatedAt: Date) -> String {
        var out: [String] = []
        let project = mission.projectLabel

        out.append("# Handoff — \(project)")
        out.append("")
        out.append("_Generated by StackPulse on \(stamp(generatedAt)) from local session data._")
        out.append("")

        // --- Session identity -------------------------------------------------
        out.append("## Session")
        out.append("")
        out.append("- **Provider:** \(mission.providerDisplay)")
        out.append("- **Status:** \(mission.statusKind.label)")
        if let model = mission.model, !model.isEmpty { out.append("- **Model:** \(model)") }
        if let branch = mission.branch, !branch.isEmpty { out.append("- **Branch:** `\(branch)`") }
        if let path = mission.project_path, !path.isEmpty { out.append("- **Path:** `\(path)`") }
        if let started = mission.startedAt { out.append("- **Started:** \(stamp(started))") }
        if let last = mission.lastActivityAt { out.append("- **Last activity:** \(stamp(last))") }
        if let count = mission.message_count { out.append("- **Turns observed:** \(count)") }
        out.append("")

        // --- What it was doing -------------------------------------------------
        if let preview = mission.last_message_preview, !preview.isEmpty {
            out.append("## Latest turn")
            out.append("")
            out.append("> \(preview)")
            out.append("")
        }

        // --- What it touched ---------------------------------------------------
        out.append("## Changed files")
        out.append("")
        if mission.changedFiles.isEmpty {
            out.append("_No uncommitted changes detected in the working tree._")
        } else {
            for f in mission.changedFiles { out.append("- `\(f)`") }
        }
        out.append("")

        // --- What that risks ---------------------------------------------------
        if !mission.scopeFlags.isEmpty {
            out.append("## Scope — review these")
            out.append("")
            for flag in mission.scopeFlags {
                let files = flag.files.isEmpty ? "" : " — " + flag.files.map { "`\($0)`" }.joined(separator: ", ")
                out.append("- **\(flag.label)** (\(flag.severity))\(files)")
            }
            out.append("")
        }

        // --- Did anything actually verify it? ----------------------------------
        out.append("## Verification")
        out.append("")
        if let v = verification {
            out.append("- **\(v.label):** \(outcome(v)) — \(stamp(v.startedAt))")
            out.append("  - `\(v.command)`")
            if !MissionEvidence.isAfterSessionStart(v, mission) {
                out.append("  - ⚠️ This run predates the session, so it does not verify this work.")
            }
        } else if let e = evidence {
            out.append("- No test/check run for this project. Most recent run was **\(e.label)**: \(outcome(e)) — \(stamp(e.startedAt)).")
        } else {
            out.append("_No captured runs for this project — **nothing here has been verified**._")
        }
        out.append("")

        // --- How to get back ---------------------------------------------------
        if let cp = checkpoints.first {
            out.append("## Restore point")
            out.append("")
            out.append("- **\(cp.label)** · `\(cp.shortID)` · \(stamp(cp.createdAt))")
            out.append("- Restore with: `\(cp.restore_command)`")
            out.append("")
        }

        out.append("---")
        out.append("")
        out.append("Read from local logs and git on this Mac. StackPulse observes the session; it does not control the agent.")
        return out.joined(separator: "\n")
    }

    private static func outcome(_ run: CommandRun) -> String {
        switch run.status {
        case .passed: return "passed (exit \(run.exitCode ?? 0))"
        case .failed: return "**FAILED** (exit \(run.exitCode ?? -1))"
        case .stopped: return "stopped before finishing"
        case .running: return "still running"
        }
    }

    private static func stamp(_ date: Date) -> String {
        let f = DateFormatter()
        f.dateStyle = .medium
        f.timeStyle = .short
        return f.string(from: date)
    }

    /// A filesystem-safe suggested filename for saving the package.
    static func suggestedFilename(for mission: Mission) -> String {
        let safe = mission.projectLabel
            .replacingOccurrences(of: "/", with: "-")
            .replacingOccurrences(of: " ", with: "-")
        return "handoff-\(safe).md"
    }
}
